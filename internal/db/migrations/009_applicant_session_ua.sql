-- Привязка сессии заявителя к устройству: в сессии фиксируется хэш
-- User-Agent (sha256, см. applicantUAHash в httpapi). Кука, выкраденная
-- вместе с трек-номером (подсмотренный экран, письмо, чат), на другом
-- устройстве не работает. Сессии, созданные до миграции (ua_hash = ''),
-- также не признаются — заявитель перелогинится по трек-номеру.
ALTER TABLE applicant_sessions ADD COLUMN IF NOT EXISTS ua_hash text NOT NULL DEFAULT '';
