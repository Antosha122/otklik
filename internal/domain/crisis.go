// CrisisWordMarkers — маркеры, проверяемые по границе слова: короткие слова,
// дающие ложные срабатывания как подстроки («нож» в «ножницах»). Слово
// считается совпавшим, если начинается с маркера и длиннее не более чем на
// 2 буквы (падежные окончания: «ножом», «пистолетом», «насилием»).
// Так «ножницы» (4 лишних буквы) не срабатывают, а реальные словоформы —
// срабатывают.
var CrisisWordMarkers = []string{
	// Опасные предметы.
	"нож", "оружие", "пистолет",

	// Физическое насилие (короткие формы бить/душить/убить).
	"бьет", "бьют", "душит", "умру", "убью", "убьет",

	// Насилие как отдельное слово.
	"насилие",
}

func normalizeCrisisText(s string) string {
	s = strings.ToLower(s)
	s = strings.ReplaceAll(s, "ё", "е")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.Join(strings.Fields(s), " ")
	return s
}

func DetectCrisis(texts ...string) bool {
	for _, raw := range texts {
		t := normalizeCrisisText(raw)
		if t == "" {
			continue
		}
		for _, m := range CrisisMarkers {
			if m != "" && strings.Contains(t, normalizeCrisisText(m)) {
				return true
			}
		}
		if matchWordMarker(t) {
			return true
		}
	}
	return false
}

// matchWordMarker проверяет слова текста против CrisisWordMarkers: слово
// совпадает, если начинается с маркера и длиннее максимум на 2 буквы
// (падежные окончания). Слова выделяются как максимальные буквенные цепочки,
// поэтому пунктуация («нож,») не мешает.
func matchWordMarker(t string) bool {
	for _, word := range splitWords(t) {
		wl := utf8.RuneCountInString(word)
		for _, m := range CrisisWordMarkers {
			// Длины сравниваем в буквах (рунах), а не байтах: кириллица — 2 байта.
			if strings.HasPrefix(word, m) && wl-utf8.RuneCountInString(m) <= 2 {
				return true
			}
		}
	}
	return false
}

func splitWords(s string) []string {
	var words []string
	var cur strings.Builder
	for _, r := range s {
		if unicode.IsLetter(r) {
			cur.WriteRune(r)
			continue
		}
		if cur.Len() > 0 {
			words = append(words, cur.String())
			cur.Reset()
		}
	}
	if cur.Len() > 0 {
		words = append(words, cur.String())
	}
	return words
}

